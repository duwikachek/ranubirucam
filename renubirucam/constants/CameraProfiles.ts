export interface CameraProfile {
  id: string;
  code: string;
  name: string;
  category: 'film' | 'instant' | 'digital-ccd' | 'toy' | 'video' | 'medium-format' | 'disposable';
  defaultAspectRatio?: '3:2' | '1:1' | '4:3';
  tagline: string;
  description: string;
  inspiration: string;
  palette: {
    primary: string;
    secondary: string;
    accent: string;
  };
  effect: {
    // Color grading (tint overlay)
    colorTint: string;
    colorTintOpacity: number; // 0–1
    // Grain
    grainIntensity: number;  // 0–100
    grainSize: 'fine' | 'medium' | 'coarse';
    // Vignette
    vignetteIntensity: number; // 0–100
    // Light leak chance
    lightLeakChance: number;  // 0–1 probability per shot
    lightLeakColor: string;
    // Contrast & brightness
    contrast: number;  // 0.5–2.0 (1.0 = normal)
    brightness: number; // -1 to 1 (0 = normal)
    saturation: number; // 0–2 (1 = normal)
    // Date stamp style
    dateStampColor: string;
    // Frame border style
    frameBorder: 'none' | 'film-strip' | 'polaroid' | 'slide' | 'dv-overlay' | 'medium-format' | 'disposable' | 'lo-fi' | 'polaroid-black';
  };
  surpriseElement: string; // Deskripsi elemen kejutan per jepretan
  shootingScenario: string[];
  tips: string[];
  icon: string; // emoji placeholder sampai aset tersedia
}

